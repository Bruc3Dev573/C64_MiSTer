#!/usr/bin/env python3
"""B8 - generate the savestate map artifacts from savestate/map.yaml.

  gen_ss_map.py            write the artifacts
  gen_ss_map.py --check    exit 1 if a committed artifact differs (CI)

Artifacts (all marked as generated, never edit them by hand):
  rtl/savestate/c64_savestates_pkg.vhd
  rtl/savestate/c64_savestates.vh
  tools/ss/ss_map.py
  docs/savestate_vice_map.md
"""
import argparse
import os
import pprint
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'savestate', 'map.yaml')
OUT = {
    'vhd': os.path.join(ROOT, 'rtl', 'savestate', 'c64_savestates_pkg.vhd'),
    'vh': os.path.join(ROOT, 'rtl', 'savestate', 'c64_savestates.vh'),
    'py': os.path.join(ROOT, 'tools', 'ss', 'ss_map.py'),
    'md': os.path.join(ROOT, 'docs', 'savestate_vice_map.md'),
}
BANNER = 'GENERATED by tools/ss/gen_ss_map.py from savestate/map.yaml - do not edit'
MAX_WORDS = 256  # A1: the plan reserved 0-127, the inventory needs ~172 words
IDENT = re.compile(r'^[A-Z][A-Z0-9_]*$')


class MapError(Exception):
    pass


def load(path=SRC):
    with open(path) as f:
        m = yaml.safe_load(f)
    return validate(m)


def validate(m):
    fmt = m['format']
    wb = fmt['word_bits']
    used = {}
    names = set()
    chain = 0
    for s in m['segments']:
        name = s['name']
        if not IDENT.match(name):
            raise MapError('segment name %r is not an identifier' % name)
        if name in names:
            raise MapError('duplicate segment %s' % name)
        names.add(name)
        a, w = s['addr'], s['words']
        if a < 0 or w <= 0 or a + w > MAX_WORDS:
            raise MapError('%s: words %d..%d outside 0..%d' % (name, a, a + w - 1, MAX_WORDS - 1))
        for i in range(a, a + w):
            if i in used:
                raise MapError('%s overlaps %s at word %d' % (name, used[i], i))
            used[i] = name
        fields = s.get('fields') or []
        fnames = set()
        bits = 0
        for f in fields:
            if f['name'] in fnames:
                raise MapError('%s: duplicate field %s' % (name, f['name']))
            fnames.add(f['name'])
            if f['bits'] <= 0:
                raise MapError('%s.%s: bits must be > 0' % (name, f['name']))
            f['offset'] = bits
            bits += f['bits']
        if bits > w * wb:
            raise MapError('%s: %d bits do not fit in %d words' % (name, bits, w))
        s['fields'] = fields
        s['chain_bits'] = bits
        s['chain_offset'] = chain
        chain += bits
    m['chain_bits'] = chain
    # chain bits carried by each 64-bit word of the CHAIN region: a segment
    # fills its words from 'addr' on, the rest of its reservation is padding
    # and the segment (index in map order, 31 = none) that owns each word:
    # the engine shifts only the segments that are instrumented ("live")
    nb = [0] * MAX_WORDS
    seg = [31] * MAX_WORDS
    for k, s in enumerate(m['segments']):
        left = s['chain_bits']
        for i in range(s['addr'], s['addr'] + s['words']):
            nb[i] = min(left, wb)
            left -= nb[i]
            seg[i] = k
    if len(m['segments']) > 31:
        raise MapError('more than 31 segments')
    m['word_nbits'] = nb
    m['word_seg'] = seg

    tags = set()
    for r in m['regions']:
        if not IDENT.match(r['name']):
            raise MapError('region name %r is not an identifier' % r['name'])
        if r['tag'] in tags or not 0 < r['tag'] < 256:
            raise MapError('region %s: bad or duplicate tag %#x' % (r['name'], r['tag']))
        tags.add(r['tag'])

    off = 0
    for c in m['config_mask']:
        c['offset'] = off
        off += c['bits']
    if off > 32:
        raise MapError('config_mask uses %d bits, max 32' % off)
    return m


def gen_vhd(m):
    fmt = m['format']
    L = ['-- ' + BANNER, '',
         'library ieee;', 'use ieee.std_logic_1164.all;', '',
         'package c64_savestates_pkg is', '',
         '\tconstant SS_FORMAT_VERSION : natural := %d;' % fmt['version'],
         '\tconstant SS_WORD_BITS      : natural := %d;' % fmt['word_bits'],
         '\tconstant SS_SLOTS          : natural := %d;' % fmt['slots'],
         '\tconstant SS_SLOT_BYTES     : natural := 16#%X#;' % fmt['slot_bytes'],
         '\tconstant SS_CHAIN_BITS     : natural := %d;' % m['chain_bits'], '',
         '\t-- scan-chain segments: legacy word address, words reserved,',
         '\t-- chain bits and offset of the first bit in the chain']
    for s in m['segments']:
        n = s['name']
        L += ['\tconstant SS_%s_ADDR   : natural := %d;' % (n, s['addr']),
              '\tconstant SS_%s_WORDS  : natural := %d;' % (n, s['words']),
              '\tconstant SS_%s_BITS   : natural := %d;' % (n, s['chain_bits']),
              '\tconstant SS_%s_OFFSET : natural := %d;' % (n, s['chain_offset'])]
        for f in s['fields']:
            L.append('\tconstant SS_%s_%s : natural := %d; -- %d bit%s' % (
                n, f['name'].upper(), f['offset'], f['bits'], '' if f['bits'] == 1 else 's'))
    L += ['', '\t-- chain bits in each 64-bit word of the CHAIN region (savestate engine)',
          '\tconstant SS_CHAIN_WORDS : natural := %d;' % MAX_WORDS,
          '\ttype ss_word_nbits_t is array (0 to %d) of natural range 0 to %d;' % (MAX_WORDS - 1, fmt['word_bits']),
          '\tconstant SS_WORD_NBITS : ss_word_nbits_t := ('] + \
         ['\t\t' + ', '.join(str(x) for x in m['word_nbits'][i:i + 16]) + (',' if i + 16 < MAX_WORDS else '')
          for i in range(0, MAX_WORDS, 16)] + ['\t);']
    L += ['\t-- segment of each word (index in map order, 31 = none)',
          '\tconstant SS_SEG_COUNT : natural := %d;' % len(m['segments']),
          '\ttype ss_word_seg_t is array (0 to %d) of natural range 0 to 31;' % (MAX_WORDS - 1),
          '\tconstant SS_WORD_SEG : ss_word_seg_t := ('] + \
         ['\t\t' + ', '.join(str(x) for x in m['word_seg'][i:i + 16]) + (',' if i + 16 < MAX_WORDS else '')
          for i in range(0, MAX_WORDS, 16)] + ['\t);']
    L += ['\tconstant SS_SEG_%s : natural := %d;' % (s['name'], k) for k, s in enumerate(m['segments'])]
    L += ['', '\t-- slot regions (TLV tags)']
    L += ['\tconstant SS_REGION_COUNT : natural := %d;' % len(m['regions'])]
    L += ['\tconstant SS_RGN_%s : natural := %d; -- region index (engine order)' % (r['name'], k)
          for k, r in enumerate(m['regions'])]
    for r in m['regions']:
        L += ['\tconstant SS_TAG_%s : natural := 16#%02X#;' % (r['name'], r['tag']),
              '\tconstant SS_%s_BYTES : natural := %d;' % (r['name'], r['bytes'])]
    L += ['', '\t-- config mask bit offsets']
    for c in m['config_mask']:
        L.append('\tconstant SS_CFG_%s : natural := %d; -- %d bit%s' % (
            c['name'].upper(), c['offset'], c['bits'], '' if c['bits'] == 1 else 's'))
    L += ['', 'end package;', '']
    return '\n'.join(L)


def gen_vh(m):
    fmt = m['format']
    L = ['// ' + BANNER, '',
         '`ifndef C64_SAVESTATES_VH', '`define C64_SAVESTATES_VH', '',
         '`define SS_FORMAT_VERSION %d' % fmt['version'],
         '`define SS_WORD_BITS %d' % fmt['word_bits'],
         '`define SS_SLOTS %d' % fmt['slots'],
         "`define SS_SLOT_BYTES 32'h%X" % fmt['slot_bytes'],
         '`define SS_CHAIN_BITS %d' % m['chain_bits'], '']
    for s in m['segments']:
        n = s['name']
        L += ['`define SS_%s_ADDR %d' % (n, s['addr']),
              '`define SS_%s_WORDS %d' % (n, s['words']),
              '`define SS_%s_BITS %d' % (n, s['chain_bits']),
              '`define SS_%s_OFFSET %d' % (n, s['chain_offset'])]
        for f in s['fields']:
            L.append('`define SS_%s_%s %d' % (n, f['name'].upper(), f['offset']))
    L += ['', '// chain bits in each 64-bit word of the CHAIN region (savestate engine):',
          '// word w is bits [7*w +: 7] of SS_WORD_NBITS',
          '`define SS_CHAIN_WORDS %d' % MAX_WORDS,
          "`define SS_WORD_NBITS {%s}" % ', '.join("7'd%d" % x for x in reversed(m['word_nbits'])),
          '// segment of each word (index in map order, 31 = none): bits [5*w +: 5]',
          '`define SS_SEG_COUNT %d' % len(m['segments']),
          "`define SS_WORD_SEG {%s}" % ', '.join("5'd%d" % x for x in reversed(m['word_seg']))]
    L += ['`define SS_SEG_%s %d' % (s['name'], k) for k, s in enumerate(m['segments'])]
    L.append('')
    n = len(m['regions'])
    L += ['// regions in engine order: tag at [8*r +: 8], size in bytes at [25*r +: 25]',
          '`define SS_REGION_COUNT %d' % n,
          "`define SS_REGION_TAGS {%s}" % ', '.join("8'h%02X" % r['tag'] for r in reversed(m['regions'])),
          "`define SS_REGION_SIZES {%s}" % ', '.join("25'd%d" % r['bytes'] for r in reversed(m['regions']))]
    L += ['`define SS_RGN_%s %d' % (r['name'], k) for k, r in enumerate(m['regions'])]
    for r in m['regions']:
        L += ["`define SS_TAG_%s 8'h%02X" % (r['name'], r['tag']),
              '`define SS_%s_BYTES %d' % (r['name'], r['bytes'])]
    L.append('')
    for c in m['config_mask']:
        L.append('`define SS_CFG_%s %d' % (c['name'].upper(), c['offset']))
    L += ['', '`endif', '']
    return '\n'.join(L)


def gen_py(m):
    data = {
        'format': m['format'],
        'chain_bits': m['chain_bits'],
        'word_nbits': m['word_nbits'],
        'word_seg': m['word_seg'],
        'segments': [{k: s[k] for k in ('name', 'addr', 'words', 'chain_bits', 'chain_offset',
                                         'instance', 'vice', 'stage', 'fields') if k in s}
                     for s in m['segments']],
        'regions': m['regions'],
        'config_mask': m['config_mask'],
    }
    return '# %s\n"""Savestate map for decode_ss.py (B6)."""\n\nMAP = %s\n' % (
        BANNER, pprint.pformat(data, width=100, sort_dicts=False))


def gen_md(m):
    L = ['<!-- %s -->' % BANNER, '', '# Savestate map and VICE correspondence', '',
         'Chain length: %d bits (fields are filled by A1 and the chip WPs; a segment with 0 bits is still a reservation).' % m['chain_bits'],
         '', '## Scan-chain segments', '',
         '| Segment | Words | Chain bits | MiSTer instance | VICE module | Stage | WP |',
         '| --- | --- | ---: | --- | --- | --- | --- |']
    for s in m['segments']:
        L.append('| %s | %d-%d | %d | `%s` | %s | %s | %s |' % (
            s['name'], s['addr'], s['addr'] + s['words'] - 1, s['chain_bits'], s['instance'],
            s.get('vice', ''), s.get('stage', ''), s.get('wp', '')))
    L += ['', '## Regions', '',
          '| Tag | Region | Bytes | Port | VICE module | Stage | Optional |',
          '| --- | --- | ---: | --- | --- | --- | --- |']
    for r in m['regions']:
        L.append('| 0x%02X | %s | %d | %s | %s | %s | %s |' % (
            r['tag'], r['name'], r['bytes'], r['port'], r.get('vice', ''), r.get('stage', ''),
            'yes' if r.get('optional') else ''))
    L += ['', '## Config mask', '', '| Bits | Name | OSD status | Note |', '| --- | --- | --- | --- |']
    for c in m['config_mask']:
        hi = c['offset'] + c['bits'] - 1
        L.append('| %s | %s | %s | %s |' % (
            str(c['offset']) if c['bits'] == 1 else '%d:%d' % (hi, c['offset']),
            c['name'], c.get('status', ''), c.get('note', '')))
    L.append('')
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    ap.add_argument('--check', action='store_true', help='fail if artifacts are stale')
    a = ap.parse_args()
    try:
        m = load()
    except (MapError, KeyError) as e:
        print('map.yaml: %s' % e, file=sys.stderr)
        return 1
    out = {'vhd': gen_vhd(m), 'vh': gen_vh(m), 'py': gen_py(m), 'md': gen_md(m)}
    stale = []
    for k, text in out.items():
        path = OUT[k]
        old = open(path).read() if os.path.exists(path) else None
        if old == text:
            continue
        if a.check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w') as f:
                f.write(text)
            print('wrote', os.path.relpath(path, ROOT))
    if stale:
        print('stale generated files (run tools/ss/gen_ss_map.py): ' + ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
